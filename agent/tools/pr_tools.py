import subprocess
import time
from pathlib import Path

from agent.tools.github_client import GitHubClient, IssueInfo


def changed_files(repo_path: Path) -> list[str]:
    out = subprocess.run(
        ["git", "-C", str(repo_path), "diff", "--name-only"],
        capture_output=True, text=True, check=True,
    ).stdout
    return [line for line in out.splitlines() if line.strip()]


def open_pull_request(
    repo_name: str, issue: IssueInfo, repo_path: Path, reasoning: str = ""
) -> str:
    """Create a branch, commit the agent's changes, open a PR, and return its URL."""
    files = changed_files(repo_path)
    if not files:
        raise ValueError("No changes to commit")

    repo = GitHubClient().gh.get_repo(repo_name)
    base = repo.default_branch
    branch = f"ai-fix/issue-{issue.number}-{time.strftime('%H%M%S')}"
    repo.create_git_ref(ref=f"refs/heads/{branch}", sha=repo.get_branch(base).commit.sha)

    for rel in files:
        content = (repo_path / rel).read_text(encoding="utf-8")
        existing = repo.get_contents(rel, ref=branch)
        repo.update_file(
            rel, f"Fix #{issue.number}: {issue.title}", content, existing.sha, branch=branch
        )

    body = (
        f"Fixes #{issue.number}\n\n"
        f"**Agent reasoning:** {reasoning}\n\n"
        "Automated fix generated by the Autonomous AI Software Engineer. "
        "The test suite passes in the Docker sandbox."
    )
    pr = repo.create_pull(
        title=f"Fix #{issue.number}: {issue.title}", body=body, head=branch, base=base
    )
    return pr.html_url